export function recordsToCSV(records: SwimRecord[]): string {
  const headers = [
    "athlete",
    "gender",
    "age_group",
    "club",
    "stroke",
    "distance",
    "split_50",
    "split_100",
    "split_150",
    "split_200",
    "total_time",
  ];
  const rows = records.map((r) => [
    r.athlete,
    r.gender,
    r.ageGroup,
    r.club,
    r.stroke,
    r.distance,
    r.splits["50"] ?? "",
    r.splits["100"] ?? "",
    r.splits["150"] ?? "",
    r.splits["200"] ?? "",
    r.totalTime,
  ]);
  return [headers.join(","), ...rows.map((row) => row.join(","))].join("\n");
}
